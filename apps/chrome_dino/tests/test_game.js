'use strict';
const assert = require('assert');
const {Game, MODES, rectsOverlap} = require('../package/javascript/src/game');
assert.strictEqual(MODES.length, 4);
assert(MODES[3].gapMin < MODES[0].gapMin);
assert(MODES[3].clusterChance > MODES[0].clusterChance);
const g = new Game({random: () => .5});
assert.strictEqual(g.state, 'ready');
g.resize(16 / 9);
g.action();
assert.strictEqual(g.state, 'playing');
assert(g.vy < 0);
const vy = g.vy;
g.action();
assert.strictEqual(g.vy, vy, 'no double-jump during flight');
g.step(1/120);
assert(g.y < g.floor);
for (let i = 0; i < 120; i++) g.step(1/120);
assert(g.y <= g.floor);
assert(g.obstacles.length > 0 || g.spawnIn > 0);
// Inject a cactus directly into the T-Rex collision box.
g.obstacles = [{x:g.x-25, y:g.floor, w:36, h:84, type:'cactus', parts:[{x:0,w:36,h:84,large:true}],scored:false}];
g.tick(1/120);
assert.strictEqual(g.state,'over');
g.action();
assert.strictEqual(g.state,'playing');
assert.strictEqual(g.score,0);
assert(g.vy<0);
assert(rectsOverlap({x:0,y:0,w:10,h:10},{x:5,y:5,w:10,h:10}));
console.log('Chrome Dino 1.4.2: jump, four modes, groups, collision and retry OK');
