'use strict';
const assert = require('assert');
const {Game, MODES, rectsOverlap} = require('../package/javascript/src/game');
assert.strictEqual(MODES.length, 3);
assert(MODES[2].gapMin < MODES[0].gapMin);
assert(MODES[2].clusterChance > MODES[0].clusterChance);
const g = new Game({random: () => .5});
assert.strictEqual(g.state, 'ready');
g.resize(16 / 9);
g.action();
assert.strictEqual(g.state, 'playing');
assert(g.vy < 0);
const vy = g.vy;
g.action();
assert.strictEqual(g.vy, vy, 'no double-jump during flight');
g.step(1/120);
assert(g.y < g.floor);
for (let i = 0; i < 120; i++) g.step(1/120);
assert(g.y <= g.floor);
assert(g.obstacles.length > 0 || g.spawnIn > 0);
// Inject a cactus directly into the T-Rex collision box.
g.obstacles = [{x:g.x-25, y:g.floor, w:36, h:84, type:'cactus', parts:[{x:0,w:36,h:84,large:true}],scored:false}];
g.tick(1/120);
assert.strictEqual(g.state,'over');
g.action();
assert.strictEqual(g.state,'playing');
assert.strictEqual(g.score,0);
assert(g.vy<0);
assert(rectsOverlap({x:0,y:0,w:10,h:10},{x:5,y:5,w:10,h:10}));
console.log('Chrome Dino 1.4.8: jump, three modes, groups, collision and retry OK');

const hard=new Game({random:()=>0.5});hard.setDifficulty(1);
const extreme=new Game({random:()=>0.5});extreme.setDifficulty(2);
assert(hard.speed>MODES[0].start,'Hard must start faster than Normal');
assert(extreme.speed>hard.speed,'Extreme must start faster than Hard');
assert(MODES[1].gapMax-MODES[1].gapMin>0.5,'Hard spacing variation too small');
assert(MODES[2].gapMax-MODES[2].gapMin>0.5,'Extreme spacing variation too small');
const ob={type:'cactus',w:60};
const seq=[0.01,0.8,0.9,0.8];let n=0;
const varied=new Game({random:()=>seq[n++%seq.length]});
varied.scheduleNext(ob);const gap1=varied.spawnIn;
varied.scheduleNext(ob);const gap2=varied.spawnIn;
assert(gap1!==gap2,'obstacle spacing must vary');
console.log('Hard / Extreme speed and varied obstacle spacing OK');
